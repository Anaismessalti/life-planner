/** Mélange déterministe (même ordre toute l'année, différent chaque année). */
function shuffled(seed: number): number[] {
  const idx = QUOTES.map((_, i) => i);
  let s = seed || 1;
  const rnd = () => ((s = (s * 1664525 + 1013904223) % 4294967296) / 4294967296);
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [idx[i], idx[j]] = [idx[j], idx[i]];
  }
  return idx;
}

/** Citation du jour : change chaque jour, aucune répétition avant d'avoir parcouru toute la bibliothèque. */
export function quoteOfDay(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  const dayOfYear = Math.round((Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 1)) / 86400000);
  const order = shuffled(y * 7919);
  return QUOTES[order[dayOfYear % order.length]];
}
